import * as Comlink from 'comlink';

class BloomFilter {
  private bitArray: Uint8Array;
  private size: number;
  private hashes: number;

  constructor(size = 10000, hashes = 3) {
    this.size = size;
    this.hashes = hashes;
    this.bitArray = new Uint8Array(Math.ceil(size / 8));
  }

  private getHashes(str: string): number[] {
    const results = [];
    let h1 = 0xdeadbeef, h2 = 0x41c6ce57;
    for (let i = 0; i < str.length; i++) {
      const ch = str.charCodeAt(i);
      h1 = Math.imul(h1 ^ ch, 2654435761);
      h2 = Math.imul(h2 ^ ch, 1597334677);
    }
    h1 = Math.imul(h1 ^ (h1 >>> 16), 2246822507) ^ Math.imul(h2 ^ (h2 >>> 13), 3266489909);
    h2 = Math.imul(h2 ^ (h2 >>> 16), 2246822507) ^ Math.imul(h1 ^ (h1 >>> 13), 3266489909);
    for (let i = 0; i < this.hashes; i++) {
      results.push(Math.abs((h1 + i * h2) % this.size));
    }
    return results;
  }

  add(str: string) {
    const hashes = this.getHashes(str);
    for (const h of hashes) {
      const byteIdx = Math.floor(h / 8);
      const bitIdx = h % 8;
      this.bitArray[byteIdx] |= (1 << bitIdx);
    }
  }

  test(str: string): boolean {
    const hashes = this.getHashes(str);
    for (const h of hashes) {
      const byteIdx = Math.floor(h / 8);
      const bitIdx = h % 8;
      if ((this.bitArray[byteIdx] & (1 << bitIdx)) === 0) {
        return false;
      }
    }
    return true;
  }
}

/**
 * Advanced Sandwiched Learned Bloom Filter (SLBF)
 * Architecture:
 * 1. Initial Bloom Filter (B1) - Filters out obvious negatives early.
 * 2. Learned ML Oracle (Online Logistic Regression Proxy) - Predicts probability of existence based on n-gram features.
 * 3. Backup Bloom Filter (B2) - Catches false negatives generated by the Oracle.
 */
class SandwichedLearnedBloomFilter {
  private initialBloom: BloomFilter;
  private backupBloom: BloomFilter;
  
  // ML Oracle Parameters (Online Logistic Regression)
  private weights: Float32Array;
  private bias: number = 0;
  private threshold: number = 0.65; // Probability threshold (Tau)

  constructor(size1 = 10000, size2 = 5000, hashes = 3, featureDim = 512) {
    this.initialBloom = new BloomFilter(size1, hashes);
    this.backupBloom = new BloomFilter(size2, hashes);
    this.weights = new Float32Array(featureDim);
  }

  // Extract character bi-gram features for the ML model
  private extractFeatures(str: string): Float32Array {
    const features = new Float32Array(this.weights.length);
    for (let i = 0; i < str.length - 1; i++) {
      const bigram = str.charCodeAt(i) + (str.charCodeAt(i+1) << 8);
      features[bigram % this.weights.length] += 1;
    }
    // L2 Normalize features
    let sum = 0;
    for (let i = 0; i < features.length; i++) sum += features[i] * features[i];
    if (sum > 0) {
      const norm = Math.sqrt(sum);
      for (let i = 0; i < features.length; i++) features[i] /= norm;
    }
    return features;
  }

  private sigmoid(z: number): number {
    return 1 / (1 + Math.exp(-z));
  }

  private predictOracle(features: Float32Array): number {
    let z = this.bias;
    for (let i = 0; i < features.length; i++) {
      z += this.weights[i] * features[i];
    }
    return this.sigmoid(z);
  }

  private trainOracle(features: Float32Array, isPositive: boolean) {
    const prediction = this.predictOracle(features);
    const target = isPositive ? 1 : 0;
    const learningRate = 0.05;
    const error = target - prediction;

    this.bias += learningRate * error;
    for (let i = 0; i < features.length; i++) {
      this.weights[i] += learningRate * error * features[i];
    }
  }

  add(str: string) {
    const features = this.extractFeatures(str);
    // Train oracle that this is a positive example (exists in set)
    this.trainOracle(features, true);
    
    this.initialBloom.add(str);
    
    // If the oracle fails to predict it (false negative from oracle), add to backup bloom filter
    if (this.predictOracle(features) < this.threshold) {
      this.backupBloom.add(str);
    }
  }

  test(str: string): boolean {
    // 1. Initial Bloom Filter (B1)
    if (!this.initialBloom.test(str)) {
      return false; // Definitely not in set
    }

    // 2. Learned Oracle
    const features = this.extractFeatures(str);
    const oracleProb = this.predictOracle(features);
    if (oracleProb >= this.threshold) {
      return true; // Oracle predicts it is in the set
    }

    // 3. Backup Bloom Filter (B2)
    return this.backupBloom.test(str);
  }
}

const SYNONYMS: Record<string, string> = {
  'pushup': 'push up',
  'elevated': 'incline',
  'db': 'dumbbell',
  'bb': 'barbell',  
  'kb': 'kettlebell',
  'bw': 'bodyweight',
  'chins': 'chin up',
  'pullups': 'pull up',
  'situp': 'sit up',
  'rdl': 'romanian deadlift'
};

class SemanticDeduplicator {
  private slbf = new SandwichedLearnedBloomFilter(10000, 5000, 4, 512);
  private exactHashes = new Set<string>();

  async normalizeAndHash(name: string): Promise<string> {
    let normalized = name.toLowerCase().replace(/[^a-z0-9\s]/g, '');
    let tokens = normalized.split(/\s+/).filter(Boolean);
    tokens = tokens.map(t => SYNONYMS[t] || t);
    tokens.sort(); // Sorting handles inversions (e.g., "Incline Push Up" vs "Push Up Incline")
    const finalStr = tokens.join('-');
    
    // Cryptographic Hash
    const encoder = new TextEncoder();
    const data = encoder.encode(finalStr);
    const hashBuffer = await crypto.subtle.digest('SHA-256', data);
    const hashArray = Array.from(new Uint8Array(hashBuffer));
    const hashHex = hashArray.map(b => b.toString(16).padStart(2, '0')).join('');
    
    return hashHex;
  }

  async checkAndAdd(name: string): Promise<{ isDuplicate: boolean, hash: string }> {
    const hash = await this.normalizeAndHash(name);
    
    // Probabilistic check via Sandwiched Learned Bloom Filter
    const mightExist = this.slbf.test(hash);
    
    if (mightExist) {
      // Secondary Semantic Collision & Detection Engine Validation
      if (this.exactHashes.has(hash)) {
        return { isDuplicate: true, hash };
      }
    }
    
    this.slbf.add(hash);
    this.exactHashes.add(hash);
    
    return { isDuplicate: false, hash };
  }

  reset() {
    this.slbf = new SandwichedLearnedBloomFilter(10000, 5000, 4, 512);
    this.exactHashes.clear();
  }
}

Comlink.expose(SemanticDeduplicator);
